import { ConflictException, Injectable } from '@nestjs/common';

@Injectable()
export class ContactsService {
    private contacts = [
        {
            id: 1,
            name: 'Alex',
            email: 'alex@example.com',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
        {
            id: 2,
            name: 'Bao',
            email: 'bao@example.com',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
        {
            id: 3,
            name: 'Daniel',
            email: 'daniel@example.com',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
    ];

    // different approach for generating ids (doesn't matter since id will later be handled by the database)
    private nextId = 4;

    findAll() {
        return this.contacts;
    }

    findOne(id: number) {
        const contact = this.contacts.find(contact => contact.id === id);

        return contact;
    }

    create(contact: { name: string, email: string }) {
        // check for duplicate emails (name can still be the same)
        // loop thru the data to see if there's no duplicates (pass the test), then return true
        const noDuplicate = this.contacts.some(c => c.email !== contact.email);
        if (!noDuplicate) throw new ConflictException('Email already exists');

        // id and dates will be generated by the server
        const newContact = {
            id: this.nextId,
            ...contact,
            createdAt: new Date(),
            updatedAt: new Date()
        }

        // update the nextId
        this.nextId += 1;

        // add to storage
        this.contacts.push(newContact);

        return newContact;
    }

    update(id: number, contactUpdate: { name?: string, email?: string }) {
        // check for duplicates (exception: user updates with the exact same email, not count as duplicate)
        const noDuplicate = this.contacts.some(c => c.id !== id && c.email !== contactUpdate.email);
        if (!noDuplicate) throw new ConflictException('Email already exists');

        this.contacts = this.contacts.map(contact => {
            if (contact.id === id) {
                return { ...contact, ...contactUpdate, updatedAt: new Date() };
            }

            return contact;
        });

        return this.findOne(id);
    }

    remove(id: number) {
        const removedContact = this.findOne(id);

        if (removedContact) {
            this.contacts = this.contacts.filter(contact => contact.id !== removedContact.id);
        }

        return removedContact;
    }
}
