import { ConflictException, Injectable, NotFoundException } from '@nestjs/common';
import { CreateContactDto } from './dto/create-contact.dto.js';
import { UpdateContactDto } from './dto/update-contact.dto.js';
import { InjectRepository } from '@nestjs/typeorm';
import { QueryFailedError, Repository } from 'typeorm';
import { Contact } from './contacts.entity.js';

@Injectable()
export class ContactsService {
    constructor(
        @InjectRepository(Contact)
        private contactsRepository: Repository<Contact>
    ) {}

    findAll() {
        return this.contactsRepository.find();
    }

    async findOne(id: number) {
        const contact = await this.contactsRepository.findOneBy({ id });

        // handle not found case and return the corresponding status/message
        if (!contact) throw new NotFoundException(`Contact ${id} not found`);

        return contact;
    }

    async create(createContactDto: CreateContactDto) {
        // check for duplicate emails (name can still be the same)
        // const isDuplicate = await this.contactsRepository.findOneBy({ email: createContactDto.email }) ? true : false;
        // if (isDuplicate) throw new ConflictException('Email already exists');

        // id and dates will be generated by the server
        const newContact = await this.contactsRepository.create(createContactDto);

        try {
            // nest handles the promise that is returned, so no need async/await + 
            // it will also display a suitable http error for us if query fail
            return await this.contactsRepository.save(newContact);
        } catch (err) {
            if (err instanceof QueryFailedError && err.driverError.code === '23505') {
                throw new ConflictException('Email already exists');
            }

            throw err; // anything else, just throw
        }
    }

    async update(id: number, updateContactDto: UpdateContactDto) {
        // check if id exists before checking for duplicates
        await this.findOne(id);

        // check for duplicates (exception: user updates with the exact same email, not count as duplicate)
        const duplicate = await this.contactsRepository
                .createQueryBuilder("contact") // alias for table name
                .where("contact.email = :email", { email: updateContactDto.email })
                .andWhere("contact.id != :id", { id: id })
                .getOne();

        if (duplicate) {
            throw new ConflictException('Email already exists');
        }

        await this.contactsRepository.update(
            id,
            updateContactDto
        );

        // return the UPDATED version
        return this.findOne(id);
    }

    async remove(id: number) {
        const removedContact = await this.findOne(id);

        // from here, contact confirm exists
        await this.contactsRepository.delete(id);

        return removedContact;
    }
}
