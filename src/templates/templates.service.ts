import { Injectable, NotFoundException } from '@nestjs/common';

@Injectable()
export class TemplatesService {
    private templates = [
        {
            id: 1,
            name: 'welcome',
            subject: 'Welcome, {{name}}!',
            body: 'Hi {{name}}, thanks for joining!',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
        {
            id: 2,
            name: 'order-shipped',
            subject: 'Your order has shipped, {{name}}',
            body: 'Hi {{name}}, your order is on its way.',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
        {
            id: 3,
            name: 'password-reset',
            subject: 'Reset your password',
            body: 'Hi {{name}}, click the link to reset your password.',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
        {
            id: 4,
            name: 'birthday',
            subject: 'Happy birthday, {{name}}!',
            body: 'Hi {{name}}, wishing you a great birthday!',
            createdAt: new Date(),
            updatedAt: new Date(),
        },
    ];

    findAll() {
        return this.templates;
    }

    findOne(id: number) {
        // find instead of filter because all template have unique ids, so there's always exactly 1 template with a specific id
        const template = this.templates.find(template => template.id === id);

        if (!template) throw new NotFoundException(`Template ${id} not found`);

        return template;
    }

    create(template: { name: string, subject: string, body: string }) {
        // id and dates will be generated by the server
        const templatesByHighestId = [...this.templates].sort( (a, b) => b.id - a.id );

        const newTemplate = {
            id: templatesByHighestId[0].id + 1,
            ...template,
            createdAt: new Date(),
            updatedAt: new Date()
        }

        this.templates.push(newTemplate);

        return newTemplate;
    }

    update(id: number, templateUpdate: { name?: string, subject?: string, body?: string }) {
        this.findOne(id);

        this.templates = this.templates.map(template => {
            if (template.id === id) {
                return { ...template, ...templateUpdate, updatedAt: new Date() }
            }

            return template;
        })

        // only for me to see the output, main thing is the above
        return this.findOne(id);
    }

    remove(id: number) {
        const removedTemplate = this.findOne(id);

        this.templates = this.templates.filter(template => template.id !== removedTemplate.id);

        return removedTemplate;
    }
}
